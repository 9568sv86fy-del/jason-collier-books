/* I-Spy game */
(() => {
  'use strict';
  if (typeof ISPY_PICS === 'undefined') return;
  const $ = s => document.querySelector(s);
  const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
  const gal = $('#ispy-gallery'), game = $('#ispy-game'), img = $('#ispy-img'), pic = $('#ispy-pic'), view = $('#ispy-view'), marks = $('#ispy-marks');
  const list = $('#ispy-items'), fEl = $('#is-found'), tEl = $('#is-time'), sEl = $('#is-score'), win = $('#ispy-win');
  const N = 10;
  let P = null, targets = [], found = new Set(), misses = 0, hints = 0, start = 0, clock = null, over = false, zoom = 1;
  gal.innerHTML = ISPY_PICS.map((p, i) => `<button type="button" class="ispy-card" role="listitem" data-i="${i}">
      <span class="ispy-card-img"><img src="${p.src}" alt="" loading="lazy"></span>
      <span class="ispy-card-t"><strong>${esc(p.title)}</strong><em>${p.items.length} things hidden · ${esc(p.credit)}</em></span></button>`).join('');
  const fmt = s => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, '0')}`;
  const secs = () => start ? (performance.now() - start) / 1000 : 0;
  const score = () => Math.max(0, found.size * 100 - misses * 10 - hints * 50);
  const shuffle = a => { a = a.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
  function hud() { fEl.textContent = found.size; sEl.textContent = score(); }
  function renderList() {
    list.innerHTML = targets.map((t, i) => `<li class="${found.has(i) ? 'done' : ''}">${esc(t.n)}</li>`).join('');
  }
  function box(t, cls, label) {
    const [x, y, w, h] = t.b, el = document.createElement('div');
    el.className = cls; el.style.cssText = `left:${x}%;top:${y}%;width:${w}%;height:${h}%`;
    if (label) el.innerHTML = `<span>${esc(label)}</span>`;
    marks.appendChild(el); return el;
  }
  function setZoom(z) {
    const cx = (view.scrollLeft + view.clientWidth / 2) / view.scrollWidth, cy = (view.scrollTop + view.clientHeight / 2) / view.scrollHeight;
    zoom = Math.min(3, Math.max(1, z)); pic.style.width = (zoom * 100) + '%';
    view.classList.toggle('zoomed', zoom > 1);
    view.scrollLeft = cx * view.scrollWidth - view.clientWidth / 2; view.scrollTop = cy * view.scrollHeight - view.clientHeight / 2;
  }
  function newRound() {
    targets = shuffle(P.items).slice(0, N); found = new Set(); misses = 0; hints = 0; start = 0; over = false;
    clearInterval(clock); tEl.textContent = '0:00'; marks.innerHTML = ''; win.hidden = true; renderList(); hud();
  }
  function open(i) {
    P = ISPY_PICS[i]; img.src = P.src; img.alt = P.title + ', ' + P.credit;
    $('#ispy-credit').textContent = P.title + ' · ' + P.credit;
    gal.hidden = true; game.hidden = false; setZoom(1); newRound();
    history.replaceState(null, '', '#' + P.id);
    game.scrollIntoView({ block: 'start' });
  }
  function close() { game.hidden = true; gal.hidden = false; clearInterval(clock); history.replaceState(null, '', location.pathname); }
  gal.addEventListener('click', e => { const b = e.target.closest('.ispy-card'); if (b) open(+b.dataset.i); });
  pic.addEventListener('click', e => {
    if (over) return;
    const r = pic.getBoundingClientRect(), px = (e.clientX - r.left) / r.width * 100, py = (e.clientY - r.top) / r.height * 100;
    if (!start) { start = performance.now(); clock = setInterval(() => tEl.textContent = fmt(secs()), 250); }
    const tol = 0.8;
    const hits = targets.map((t, i) => ({ t, i })).filter(({ t, i }) => !found.has(i) && px >= t.b[0] - tol && px <= t.b[0] + t.b[2] + tol && py >= t.b[1] - tol && py <= t.b[1] + t.b[3] + tol)
      .sort((a, b) => a.t.b[2] * a.t.b[3] - b.t.b[2] * b.t.b[3]);
    if (hits.length) {
      const { t, i } = hits[0]; found.add(i); box(t, 'mk-found', '✓ ' + t.n); renderList(); hud();
      if (found.size === targets.length) {
        over = true; clearInterval(clock);
        $('#ispy-win-text').textContent = `Time ${fmt(secs())} · Score ${score()} · ${misses} miss${misses === 1 ? '' : 'es'}${hints ? ` · ${hints} hint${hints === 1 ? '' : 's'}` : ''}`;
        win.hidden = false;
      }
    } else {
      misses++; hud();
      const m = document.createElement('div'); m.className = 'mk-miss'; m.style.cssText = `left:${px}%;top:${py}%`;
      marks.appendChild(m); setTimeout(() => m.remove(), 800);
    }
  });
  $('#is-hint').addEventListener('click', () => {
    if (over) return;
    const left = targets.map((t, i) => i).filter(i => !found.has(i)); if (!left.length) return;
    hints++; hud();
    const t = targets[left[Math.floor(Math.random() * left.length)]];
    const [x, y, w, h] = t.b, pad = Math.max(w, h) * .6;
    const el = box({ b: [Math.max(0, x - pad), Math.max(0, y - pad), Math.min(100, w + pad * 2), Math.min(100, h + pad * 2)] }, 'mk-hint');
    setTimeout(() => el.remove(), 2200);
    if (zoom > 1) { view.scrollLeft = (x + w / 2) / 100 * view.scrollWidth - view.clientWidth / 2; view.scrollTop = (y + h / 2) / 100 * view.scrollHeight - view.clientHeight / 2; }
  });
  $('#is-new').addEventListener('click', newRound);
  $('#is-again').addEventListener('click', newRound);
  $('#is-back').addEventListener('click', close);
  $('#is-other').addEventListener('click', close);
  $('#is-zin').addEventListener('click', () => setZoom(zoom + .5));
  $('#is-zout').addEventListener('click', () => setZoom(zoom - .5));
  const h = location.hash.slice(1), k = ISPY_PICS.findIndex(p => p.id === h);
  if (k >= 0) open(k);
  window.__ispy = { open, get targets() { return targets; }, get found() { return found.size; }, pic };
})();
